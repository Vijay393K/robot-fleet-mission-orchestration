
CREATE TABLE robot_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    robot_id UUID NOT NULL,

    sequence_number BIGINT NOT NULL,
    battery_percentage INTEGER NOT NULL,
    location_x DOUBLE PRECISION NOT NULL,
    location_y DOUBLE PRECISION NOT NULL,
    speed DOUBLE PRECISION NOT NULL,
    health_status VARCHAR(20) NOT NULL,
    telemetry_timestamp TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_telemetry_robot
        FOREIGN KEY (robot_id) REFERENCES robots(id),

    CONSTRAINT chk_telemetry_battery
        CHECK (battery_percentage BETWEEN 0 AND 100),

    CONSTRAINT chk_telemetry_speed
        CHECK (speed >= 0),

    CONSTRAINT chk_telemetry_health
        CHECK (health_status IN ('HEALTHY', 'WARNING', 'ERROR')),

    CONSTRAINT uq_robot_telemetry_sequence
        UNIQUE (robot_id, sequence_number)
);

CREATE INDEX idx_telemetry_robot_timestamp
    ON robot_telemetry (robot_id, telemetry_timestamp DESC);

CREATE INDEX idx_telemetry_received_at
    ON robot_telemetry (received_at);
