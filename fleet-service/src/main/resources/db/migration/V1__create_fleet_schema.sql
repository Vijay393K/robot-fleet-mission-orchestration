
CREATE TABLE robots (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(20) NOT NULL
        CHECK (type IN ('PICKER', 'CARRIER', 'INSPECTION')),
    battery_percentage INTEGER NOT NULL
        CONSTRAINT ck_robots_battery_range
        CHECK (battery_percentage BETWEEN 0 AND 100),
    location_x DOUBLE PRECISION NOT NULL,
    location_y DOUBLE PRECISION NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('IDLE', 'BUSY', 'CHARGING', 'OFFLINE', 'ERROR')),
    last_heartbeat TIMESTAMPTZ,
    current_mission_id UUID,
    current_session_id UUID,
    last_heartbeat_sequence BIGINT NOT NULL DEFAULT 0,
    safety_hold BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE robot_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_id UUID NOT NULL,
    sequence_number BIGINT NOT NULL,
    session_id UUID NOT NULL,
    battery_percentage INTEGER NOT NULL
        CONSTRAINT ck_telemetry_battery_range
        CHECK (battery_percentage BETWEEN 0 AND 100),
    location_x DOUBLE PRECISION NOT NULL,
    location_y DOUBLE PRECISION NOT NULL,
    speed DOUBLE PRECISION NOT NULL
        CONSTRAINT ck_telemetry_speed_non_negative
        CHECK (speed >= 0),
    health_status VARCHAR(20) NOT NULL
        CHECK (health_status IN ('HEALTHY', 'WARNING', 'ERROR')),
    telemetry_timestamp TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_telemetry_robot
        FOREIGN KEY (robot_id) REFERENCES robots(id),
    CONSTRAINT ck_telemetry_sequence_positive
        CHECK (sequence_number > 0),
    CONSTRAINT uq_robot_telemetry_session_sequence
        UNIQUE (robot_id, session_id, sequence_number)
);

CREATE INDEX idx_telemetry_robot_timestamp
    ON robot_telemetry (robot_id, telemetry_timestamp DESC);

CREATE INDEX idx_telemetry_received_at
    ON robot_telemetry (received_at);

CREATE INDEX idx_robot_telemetry_latest
    ON robot_telemetry (
        robot_id,
        telemetry_timestamp DESC,
        id DESC
    );

CREATE TABLE robot_heartbeats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_id UUID NOT NULL,
    session_id UUID,
    sequence_number BIGINT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_robot_heartbeats_robot
        FOREIGN KEY (robot_id) REFERENCES robots(id),
    CONSTRAINT uq_robot_heartbeats_robot_sequence
        UNIQUE (robot_id, sequence_number),
    CONSTRAINT ck_robot_heartbeats_sequence_positive
        CHECK (sequence_number > 0)
);

CREATE INDEX idx_robot_heartbeats_robot_received_at
    ON robot_heartbeats (robot_id, received_at DESC);

CREATE TABLE robot_reservations (
    id UUID PRIMARY KEY,
    robot_id UUID NOT NULL,
    mission_id UUID NOT NULL,
    operation_scope VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('RESERVED', 'CONFIRMED', 'RELEASED', 'EXPIRED')),
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    released_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reservation_robot
        FOREIGN KEY (robot_id) REFERENCES robots(id),
    CONSTRAINT ck_reservation_expiry
        CHECK (expires_at > reserved_at),
    CONSTRAINT uq_reservation_scope_key
        UNIQUE (operation_scope, idempotency_key)
);

CREATE UNIQUE INDEX uq_active_reservation_per_robot
    ON robot_reservations (robot_id)
    WHERE status IN ('RESERVED', 'CONFIRMED');

CREATE UNIQUE INDEX uq_active_reservation_per_mission
    ON robot_reservations (mission_id)
    WHERE status IN ('RESERVED', 'CONFIRMED');

CREATE INDEX idx_reservations_expiry
    ON robot_reservations (expires_at)
    WHERE status = 'RESERVED';

CREATE INDEX idx_reservations_mission
    ON robot_reservations (mission_id, created_at DESC);
